#!/usr/bin/env python3
"""Color children the game gives objects inside real levels, mined from the harness's scene dumps.

The synthetic-level sprite dump (visuals.rs) lacks some color sprites the game only adds in
levels (block009_05 gets block009_06_color, ...). Every real screenshot's `.scene` lists each
GameObject with its children; this collects, per main frame, the `_color_` child (frame, local
position, z) seen most often.

Usage: gen_color_children.py shots/*/real-*.png.scene > crates/cadence-game/src/color_children.rs
"""
import re
import sys
from collections import Counter, defaultdict

LINE = re.compile(r"^(\s*)(\S+) tag=\S+ z=(-?\d+) pos=([-\d.]+),([-\d.]+) .*? vis=(\d) op=(\d+) .*? frame=(\S+) kids=(\d+)")


def signature(main, kids):
    """An object's identity as both sides can see it: its frame and its direct children's."""
    return main + "|" + ",".join(sorted(kids))


def main():
    # object signature -> Counter of its color sprite (the z 100 child: frame, x, y)
    seen = defaultdict(Counter)
    objects = Counter()

    def finish(o):
        if o:
            sig = signature(o["frame"], o["kids"])
            objects[sig] += 1
            if o["color"]:
                seen[sig][o["color"]] += 1

    for path in sys.argv[1:]:
        obj = None
        for line in open(path):
            m = LINE.match(line)
            if not m:
                continue
            indent, kind, z, x, y = len(m.group(1)), m.group(2), int(m.group(3)), float(m.group(4)), float(m.group(5))
            frame = m.group(8)
            if obj and indent <= obj["indent"]:
                finish(obj)
                obj = None
            if "GameObject" in kind:
                obj = {"indent": indent, "frame": frame, "kids": [], "color": None, "child": None} if frame.endswith("_001.png") else None
                continue
            if not obj:
                continue
            if obj["child"] is None or indent <= obj["child"]:
                obj["child"] = indent
            if indent != obj["child"]:
                continue  # grandchildren
            if obj["color"] is None and ((z == 100 and frame == obj["frame"]) or "_color_" in frame):
                obj["color"] = (frame, round(x, 2), round(y, 2), z)
            elif frame.endswith("_001.png") and "_glow_" not in frame and "_color_" not in frame:
                obj["kids"].append(frame)
        finish(obj)
    print("// @generated by tools/gen_color_children.py from real scene dumps. Do not edit.")
    print("// An object's color sprite as the game adds it in levels (`GameObject::addColorSprite`):")
    print("// (object signature: frame|children's frames, color sprite frame, x, y). It is a z 100 child")
    print("// in the detail color: the frame's `_color` version, or for objects of several parts a copy")
    print("// of the main frame holding the parts' `_color` versions (z -1, at the parts' positions).")
    print()
    print("pub static COLOR_CHILDREN: &[(&str, &str, f32, f32, i16)] = &[")
    for sig in sorted(seen):
        (frame, x, y, z), n = seen[sig].most_common(1)[0]
        if n * 2 < objects[sig]:
            continue
        print(f'    ("{sig}", "{frame}", {x:.2f}, {y:.2f}, {z}),')
    print("];")


def glows(paths):
    """Glow sprites sit in their own batch node at their object's world position: match them."""
    seen = defaultdict(Counter)
    objects = Counter()
    for path in paths:
        objs = {}  # rounded pos -> signature
        glow_at = {}
        obj = None
        for line in open(path):
            m = LINE.match(line)
            if not m:
                continue
            indent, kind, x, y, frame = len(m.group(1)), m.group(2), float(m.group(4)), float(m.group(5)), m.group(8)
            if obj and indent <= obj["indent"]:
                objs.setdefault(obj["pos"], signature(obj["frame"], obj["kids"]))
                obj = None
            if "GameObject" in kind:
                if frame.endswith("_glow_001.png"):
                    glow_at[(round(x, 1), round(y, 1))] = frame
                elif frame.endswith("_001.png"):
                    obj = {"indent": indent, "frame": frame, "kids": [], "pos": (round(x, 1), round(y, 1)), "child": None}
                continue
            if obj:
                if obj["child"] is None or indent <= obj["child"]:
                    obj["child"] = indent
                if indent == obj["child"] and int(m.group(3)) != 100 and frame.endswith("_001.png") and "_glow_" not in frame and "_color_" not in frame:
                    obj["kids"].append(frame)
            elif frame.endswith("_glow_001.png"):
                glow_at[(round(x, 1), round(y, 1))] = frame
        for pos, sig in objs.items():
            objects[sig] += 1
            if pos in glow_at:
                seen[sig][glow_at[pos]] += 1
    print()
    print("// Object signature -> the glow frame the game draws for it (matched by position).")
    print("pub static GLOWS: &[(&str, &str)] = &[")
    for sig in sorted(seen):
        frame, n = seen[sig].most_common(1)[0]
        if n * 3 < objects[sig]:
            continue
        print(f'    ("{sig}", "{frame}"),')
    print("];")


if __name__ == "__main__":
    main()
