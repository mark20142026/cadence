#!/usr/bin/env python3
"""Generate crates/cadence-core/src/objects/visuals.rs from the harness sprite dump.

Input: re/traces/sprites-level.tsv (+ .objects), from `dumpsprites` on the synthetic level that
holds every object, so children that only exist inside a level are included.

Usage: gen_sprite_table.py re/traces/sprites-level.tsv > crates/cadence-core/src/objects/visuals.rs
       gen_sprite_table.py --color-z re/traces/sprites-level.tsv > crates/cadence-game/src/color_z.rs
       gen_sprite_table.py --spin re/traces/sprites-level.tsv > crates/cadence-game/src/spin.rs
"""
import csv
import sys


def num(v):
    s = repr(float(v))
    return s if ("." in s or "e" in s or "inf" in s) else s + ".0"


def color_z(path):
    """`--color-z`: the ids whose m_colorZLayerRelated (GameObject+0x41d) is set, for the app."""
    ids = sorted(int(r["id"]) for r in csv.DictReader(open(path + ".objects"), delimiter="\t") if r.get("color_z_related") == "1")
    print("// @generated by tools/gen_sprite_table.py --color-z from a real-game sprite dump. Do not edit.")
    print("// Object ids whose m_colorZLayerRelated (GameObject+0x41d) is set: when only one of the main and")
    print("// detail sprites blends, the detail moves a z layer up (else the main does).")
    print()
    print("pub static COLOR_Z_RELATED: &[u16] = &[")
    for i in range(0, len(ids), 16):
        print("    " + ", ".join(str(v) for v in ids[i:i + 16]) + ",")
    print("];")


def spin(path):
    """`--spin`: per id, the spin rate (degrees/s) the game gave it in the dump
    (EnhancedGameObject+0x578, set in `customSetup` 0x5bb8dc; partly random per object)."""
    rows = [r for r in csv.DictReader(open(path + ".objects"), delimiter="\t") if float(r.get("rotation_rate") or 0) != 0]
    print("// @generated by tools/gen_sprite_table.py --spin from a real-game sprite dump. Do not edit.")
    print("// Object ids that spin in play and the |rate| (degrees per second) one dump gave them. The game")
    print("// picks the direction (and for most decorations the speed) with rand() per object.")
    print()
    print("pub static SPIN: &[(u16, f32)] = &[")
    for r in sorted(rows, key=lambda r: int(r["id"])):
        print(f"    ({int(r['id'])}, {num(abs(float(r['rotation_rate'])))}),")
    print("];")


def black(path):
    """`--black`: ids whose main sprite stays black whatever its channel (m_isObjectBlack,
    GameObject+0x281: `setObjectColor` 0x5b8708 skips setColor for them)."""
    ids = sorted(int(r["id"]) for r in csv.DictReader(open(path + ".objects"), delimiter="\t") if r.get("object_black") == "1")
    print("// @generated by tools/gen_sprite_table.py --black from a real-game sprite dump. Do not edit.")
    print("// Object ids whose main sprite stays black (m_isObjectBlack): the game never tints it.")
    print()
    print("pub static OBJECT_BLACK: &[u16] = &[")
    for i in range(0, len(ids), 16):
        print("    " + ", ".join(str(v) for v in ids[i:i + 16]) + ",")
    print("];")
    rows = sorted((int(r["id"]), float(r["black_child_opacity"] or 0)) for r in csv.DictReader(open(path + ".objects"), delimiter="\t")
                  if r.get("color_sprite_black") == "1")
    print()
    print("/// Ids whose child sprites stay black (m_isColorSpriteBlack, +0x280), with m_blackChildOpacity")
    print("/// (+0x284; 0 = opaque).")
    print("pub static CHILD_BLACK: &[(u16, f32)] = &[")
    for oid, op in rows:
        print(f"    ({oid}, {num(op)}),")
    print("];")
    glows = sorted((int(r["id"]), r.get("glow_lbg") == "1") for r in csv.DictReader(open(path + ".objects"), delimiter="\t")
                   if r.get("custom_glow_color") == "1")
    print()
    print("/// Ids whose glow is tinted (m_customGlowColor, +0x431): with the light background (true,")
    print("/// m_glowColorIsLBG +0x432) or the background shifted s −0.2 v +0.2 (false).")
    print("pub static GLOW_COLOR: &[(u16, bool)] = &[")
    for oid, lbg in glows:
        print(f"    ({oid}, {'true' if lbg else 'false'}),")
    print("];")


def main():
    if sys.argv[1] == "--color-z":
        return color_z(sys.argv[2])
    if sys.argv[1] == "--spin":
        return spin(sys.argv[2])
    if sys.argv[1] == "--black":
        return black(sys.argv[2])
    path = sys.argv[1]
    meta = {int(r["id"]): r for r in csv.DictReader(open(path + ".objects"), delimiter="\t")}
    sprites = {}
    for r in csv.DictReader(open(path), delimiter="\t"):
        # the detached color sprite of the synthetic level is often empty; the color sprites a
        # level gives objects come from real scene dumps (color_children.rs)
        if r["path"].startswith("color"):
            continue
        sprites.setdefault(int(r["id"]), []).append(r)

    print("// @generated by tools/gen_sprite_table.py from a real-game sprite dump. Do not edit.")
    print("// Per object id: default colors and z, and the sprite tree as the game builds it inside a")
    print("// level (frame names, local transforms in the parent's content space, z, blending).")
    print()
    print("use super::{ObjectVisual, SpriteDef, SpriteRole};")
    print()
    print("pub static VISUALS: &[ObjectVisual] = &[")
    for oid in sorted(sprites):
        m = meta.get(oid)
        if m is None:
            continue
        rows = sprites[oid]
        index = {}
        defs = []
        for r in rows:
            index[r["path"]] = len(index)
        for r in rows:
            parent_path = r["path"].rsplit("/", 1)[0] if "/" in r["path"] else None
            parent = index.get(parent_path, -1) if parent_path else -1
            role = {"main": "Main", "detail": "Detail", "glow": "Glow"}.get(r["role"], "Child")
            frame = r["frame"] if r["frame"] not in ("-", "?") else ""
            main = r["role"] == "main"
            defs.append(
                f"SpriteDef {{ parent: {parent}, role: SpriteRole::{role}, frame: {frame!r}, "
                f"x: {num(0 if main else r['x'])}, y: {num(0 if main else r['y'])}, "
                f"anchor_x: {num(r['anchor_x'])}, anchor_y: {num(r['anchor_y'])}, "
                f"w: {num(r['w'])}, h: {num(r['h'])}, scale_x: {num(r['scale_x'])}, scale_y: {num(r['scale_y'])}, "
                f"rotation: {num(r['rot'])}, z: {int(r['z'])}, visible: {'true' if main or r['visible'] == '1' else 'false'}, "
                f"flip_x: {'true' if r['flip_x'] == '1' else 'false'}, flip_y: {'true' if r['flip_y'] == '1' else 'false'}, "
                f"additive: {'true' if r['blend_dst'] == '1' else 'false'} }}"
            )
        sprites_src = ", ".join(defs).replace("'", '"')
        print(
            f"    ObjectVisual {{ id: {oid}, base_color: {int(m['base_color'])}, detail_color: {int(m['detail_color'])}, "
            f"z_layer: {int(m['z_layer'])}, z_order: {int(m['z_order'])}, glow: {'true' if m['glow'] == '1' else 'false'}, "
            f"sprites: &[{sprites_src}] }},"
        )
    print("];")


if __name__ == "__main__":
    main()
