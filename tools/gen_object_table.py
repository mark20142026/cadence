#!/usr/bin/env python3
"""Generate crates/cadence-core/src/objects/table.rs from a harness object dump.

The dump comes from loading a synthetic level that contains every object id into the real game
(harness spec `levelstring` + `dumplevel`). Each row gives the game's own type and collision
rectangle for that id, measured relative to the object's position.

Usage: gen_object_table.py <dump.csv>... > crates/cadence-core/src/objects/table.rs
Earlier dumps win; later ones fill ids the earlier ones lack (the synthetic level drops secret
coins, id 142, which only exist in official levels, so a main-level dump supplies them).
Only unrotated, unscaled objects are used as the reference for an id.
"""
import csv
import sys


def num(v):
    f = float(v)
    s = repr(f)
    return s if "." in s or "e" in s else s + ".0"


def main():
    rows = {}
    for path in sys.argv[1:]:
        for r in csv.DictReader(open(path)):
            plain = float(r.get("rot", 0)) == 0 and r.get("scale_x", "1") == "1" and r.get("scale_y", "1") == "1"
            if int(r["id"]) > 0 and plain:  # id 0: the game's own end-of-level object
                rows.setdefault(int(r["id"]), r)
    max_id = max(rows)
    print("// @generated by tools/gen_object_table.py from a real-game object dump. Do not edit.")
    print("// Per object id: type, collision rect offset/size relative to the object position")
    print("// (unrotated, unscaled), base size and radius.")
    print()
    print("use super::{ObjectInfo, ObjectType};")
    print()
    print(f"pub const MAX_ID: usize = {max_id};")
    print()
    print("pub static OBJECTS: &[ObjectInfo] = &[")
    for oid in sorted(rows):
        r = rows[oid]
        dx = float(r["rect_x"]) - float(r["x"])
        dy = float(r["rect_y"]) - float(r["y"])
        print(
            f"    ObjectInfo {{ id: {oid}, kind: ObjectType({r['type']}), "
            f"rect_x: {num(dx)}, rect_y: {num(dy)}, rect_w: {num(r['rect_w'])}, rect_h: {num(r['rect_h'])}, "
            f"width: {num(r['width'])}, height: {num(r['height'])}, radius: {num(r['radius'])} }},"
        )
    print("];")


if __name__ == "__main__":
    main()
